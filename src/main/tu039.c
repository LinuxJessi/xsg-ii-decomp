void _CurMatrixScale(Vector4 *scale) {
    __asm__ __volatile__(
        "lqc2 vf31, 0(%0)\n"
        "vmulx.xyz vf27, vf27, vf31x\n"
        "vmuly.xyz vf28, vf28, vf31y\n"
        "vmulz.xyz vf29, vf29, vf31z\n"
        :
        : "r" (scale)
        : "memory");
}

int _CurRotTransPersClipScreen(Vector4 *screenOut, const Vector4 *point) {
    register int clipFlags;

    __asm__ __volatile__(
        "ctc2 $0, $vi18\n"
        "lqc2 vf31, 0(%2)\n"
        "vmulax.xyzw ACC, vf27, vf31x\n"
        "vmadday.xyzw ACC, vf28, vf31y\n"
        "vmaddaz.xyzw ACC, vf29, vf31z\n"
        "vmaddw.xyzw vf31, vf30, vf0w\n"
        "vnop\n"
        "vnop\n"
        "vnop\n"
        "vclipw.xyz vf31, vf31w\n"
        "vdiv Q, vf0w, vf31w\n"
        "vwaitq\n"
        "vmulq.xyzw vf31, vf31, Q\n"
        "vmulq.w vf23, vf0w, Q\n"
        "vmulaw.xyzw ACC, vf26, vf0w\n"
        "vmadd.xyzw vf31, vf31, vf25\n"
        "vftoi4.xy vf23, vf31\n"
        "vftoi0.z vf23, vf31\n"
        "sqc2 vf23, 0(%1)\n"
        "cfc2 $2, $vi18\n"
        "nop\n"
        "andi $2, $2, 0x3f\n"
        "move %0, $2\n"
        : "=r" (clipFlags)
        : "r" (screenOut), "r" (point)
        : "$2", "memory");

    return clipFlags;
}

